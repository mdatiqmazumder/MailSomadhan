"""One-click import of cPanel email backup archives (.tar.gz / .tgz / .zip) into MailSomadhan.

Supports:
1. Archives generated by `cpanel-migrate.sh` (containing `backup_manifest.json` + `mailboxes/<email>/...`
   + original cPanel shadow password hashes).
2. Raw cPanel Maildir/Homedir archives (containing `mail/<domain>/<local_part>/{cur,new,.Sent,...}` and
   optionally `etc/<domain>/shadow`).

Preserves the exact same cPanel email passwords by default (using the shadow password hash from cPanel,
understood by both Dovecot IMAP/SMTP and MailSomadhan Webmail), or generates random passwords when requested.
"""
