def normalize_cpanel_shadow_hash(raw_hash: str) -> str:
    """Convert a raw hash field from cPanel's `etc/<domain>/shadow` into a Dovecot & MailSomadhan
    compatible `{SCHEME}...` password_hash string."""
    h = raw_hash.strip()
    if not h or h in ("*", "!", "!!", "x", "*LK*", "NP"):
        return ""
    if h.startswith("{"):
        return h
    if h.startswith("$6$"):
        return "{SHA512-CRYPT}" + h
    if h.startswith("$5$"):
        return "{SHA256-CRYPT}" + h
    if h.startswith("$1$"):
        return "{MD5-CRYPT}" + h
    if h.startswith(("$2a$", "$2b$", "$2y$")):
        return "{BLF-CRYPT}" + h
    if h.startswith("$"):
        return "{CRYPT}" + h
    return ""


def parse_shadow_text(content: str, domain: str) -> dict[str, str]:
    """Parse `etc/<domain>/shadow` content and return `{email: normalized_dovecot_hash}`."""
    out: dict[str, str] = {}
    dom = domain.strip().lower()
    for line in content.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        parts = line.split(":")
        local_part = parts[0].strip().lower()
        raw_hash = parts[1].strip() if len(parts) > 1 else ""
        if not local_part:
            continue
        norm = normalize_cpanel_shadow_hash(raw_hash)
        if norm:
            email_key = local_part if "@" in local_part else f"{local_part}@{dom}"
            out[email_key] = norm
    return out


def generate_random_password(length: int = 16) -> str:
    """Generate a strong random password when no shadow hash is used."""
    length = max(12, min(length, 64))
    upper = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    lower = "abcdefghijkmnopqrstuvwxyz"
    digits = "23456789"
    symbols = "!@#$%&*-+="
    rng = secrets.SystemRandom()

    chars = [
        rng.choice(upper),
        rng.choice(upper),
        rng.choice(upper),
        rng.choice(lower),
        rng.choice(lower),
        rng.choice(lower),
        rng.choice(digits),
        rng.choice(digits),
        rng.choice(digits),
        rng.choice(symbols),
    ]
    pool = upper + lower + digits
    while len(chars) < length:
        chars.append(rng.choice(pool))
    rng.shuffle(chars)
    if chars[0] in symbols:
        for i, ch in enumerate(chars):
            if ch not in symbols:
                chars[0], chars[i] = chars[i], chars[0]
                break
    return "".join(chars)


def _imap_quote(name: str) -> str:
    return '"' + encode_mutf7(name).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _clamp_ts(ts: float) -> float:
    min_ts = 946684800.0  # 2000-01-01
    max_ts = time.time() + 86400.0
    if ts < min_ts or ts > max_ts:
        return time.time()
    return ts


def map_folder_name(raw_folder_name: str, flags: list[str] | None = None, delim: str = ".") -> tuple[str, str]:
    lower_flags = {f.lower() for f in (flags or [])}
    cleaned = raw_folder_name.strip()
    if cleaned.upper() == "INBOX":
        return "INBOX", "inbox"

    if cleaned.upper().startswith("INBOX.") or cleaned.upper().startswith("INBOX/"):
        stripped = cleaned[6:]
    elif cleaned.startswith(".") and len(cleaned) > 1:
        stripped = cleaned[1:]
    else:
        stripped = cleaned

    norm = stripped.replace(delim or ".", "/").strip("/")
    low = norm.lower()

    if "\\sent" in lower_flags or low in ("sent", "sent messages", "sent items", "sent mail"):
        return "Sent", "sent"
    if "\\drafts" in lower_flags or low in ("drafts", "draft"):
        return "Drafts", "drafts"
    if "\\junk" in lower_flags or "\\spam" in lower_flags or low in ("junk", "spam", "junk mail", "junk e-mail", "bulk mail"):
        return "Junk", "junk"
    if "\\trash" in lower_flags or low in ("trash", "deleted", "deleted items", "deleted messages", "bin"):
        return "Trash", "trash"
    if "\\archive" in lower_flags or low in ("archive", "archives"):
        return "Archive", "archive"

    safe_parts = [re.sub(r'[\x00-\x1f\x7f"\\*%]', "_", p).strip() for p in norm.split("/") if p.strip()]
    target = "/".join(safe_parts) if safe_parts else "Archive"
    return target[:80], "custom"


def parse_eml_bytes(
    raw_bytes: bytes,
    flags: list[str],
    internal_ts: float,
    target_folder: str,
    role: str,
    eml_path: Path,
) -> dict[str, Any]:
    msg = email.message_from_bytes(raw_bytes, policy=email.policy.default)

    def hdr(name: str) -> str:
        try:
            return str(msg.get(name) or "").strip()
        except Exception:
            return ""

    date_hdr = hdr("Date")
    if date_hdr:
        try:
            dt = email.utils.parsedate_to_datetime(date_hdr)
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=datetime.timezone.utc)
            internal_ts = _clamp_ts(dt.timestamp())
        except Exception:
            internal_ts = _clamp_ts(internal_ts)
    else:
        internal_ts = _clamp_ts(internal_ts)

    message_id = hdr("Message-ID")
    if not message_id:
        digest = hashlib.sha256(raw_bytes).hexdigest()[:32]
        message_id = f"<sha256-{digest}@mailsomadhan.imported>"

    from_addrs = [addr.lower() for _, addr in email.utils.getaddresses([hdr("From")]) if "@" in addr]
    to_addrs = [
        addr.lower()
        for _, addr in email.utils.getaddresses([hdr("To"), hdr("Cc"), hdr("Delivered-To"), hdr("X-Original-To")])
        if "@" in addr
    ]
    has_attachment = False
    try:
        for part in msg.walk():
            if part.is_multipart():
                continue
            if part.get_content_disposition() == "attachment" or part.get_filename():
                has_attachment = True
                break
    except Exception:
        pass

    allowed_flags = {"\\seen": "\\Seen", "\\answered": "\\Answered", "\\flagged": "\\Flagged", "\\draft": "\\Draft"}
    clean_flags = []
    for f in flags:
        mapped = allowed_flags.get(f.lower())
        if mapped and mapped not in clean_flags:
            clean_flags.append(mapped)

    return {
        "eml_path": eml_path,
        "target_folder": target_folder,
        "role": role,
        "flags": clean_flags,
        "internal_ts": internal_ts,
        "message_id": message_id[:500],
        "subject": hdr("Subject")[:500],
        "sender": (from_addrs[0] if from_addrs else "")[:320],
        "recipients": to_addrs[:50],
        "size": len(raw_bytes),
        "has_attachment": has_attachment,
    }


def _safe_extract_archive(archive_path: Path, extract_dir: Path) -> None:
    name_low = archive_path.name.lower()
    resolved_root = extract_dir.resolve()

    if name_low.endswith(".zip"):
        try:
            with zipfile.ZipFile(archive_path, "r") as zf:
                for member in zf.infolist():
                    if member.is_dir():
                        continue
                    rel = Path(member.filename)
                    if rel.is_absolute() or ".." in rel.parts:
                        continue
                    target = (resolved_root / rel).resolve()
                    if not str(target).startswith(str(resolved_root)):
                        continue
                    target.parent.mkdir(parents=True, exist_ok=True)
                    with zf.open(member, "r") as src, open(target, "wb") as dst:
                        shutil.copyfileobj(src, dst)
            return
        except zipfile.BadZipFile as exc:
            raise HTTPException(400, f"Invalid ZIP archive: {exc}") from exc

    try:
        with tarfile.open(archive_path, "r:*") as tf:
            for member in tf.getmembers():
                if not member.isfile():
                    continue
                rel = Path(member.name)
                if rel.is_absolute() or ".." in rel.parts:
                    continue
                target = (resolved_root / rel).resolve()
                if not str(target).startswith(str(resolved_root)):
                    continue
                target.parent.mkdir(parents=True, exist_ok=True)
                src = tf.extractfile(member)
                if src is not None:
                    with src, open(target, "wb") as dst:
                        shutil.copyfileobj(src, dst)
                    if member.mtime:
                        try:
                            os.utime(target, (member.mtime, member.mtime))
                        except OSError:
                            pass
    except (tarfile.TarError, OSError) as exc:
        raise HTTPException(400, f"Could not read backup archive (.tar.gz / .tgz / .zip expected): {exc}") from exc


def _discover_shadow_hashes(extract_dir: Path) -> dict[str, str]:
    """Find any `etc/<domain>/shadow` or `shadow/<domain>.shadow` files in the archive."""
    shadow_map: dict[str, str] = {}
    for p in extract_dir.rglob("*"):
        if not p.is_file():
            continue
        if p.name == "shadow" and DOMAIN_RE.match(p.parent.name.lower()):
            try:
                shadow_map.update(parse_shadow_text(p.read_text(encoding="utf-8", errors="replace"), p.parent.name.lower()))
            except OSError:
                pass
        elif p.name.endswith(".shadow") and DOMAIN_RE.match(p.name[:-7].lower()):
            dom = p.name[:-7].lower()
            try:
                shadow_map.update(parse_shadow_text(p.read_text(encoding="utf-8", errors="replace"), dom))
            except OSError:
                pass
    return shadow_map


def _discover_accounts_from_extracted(extract_dir: Path) -> list[dict[str, Any]]:
    shadow_hashes = _discover_shadow_hashes(extract_dir)

    manifests = list(extract_dir.rglob("backup_manifest.json"))
    if manifests:
        manifest_path = manifests[0]
        base_dir = manifest_path.parent
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception as exc:
            raise HTTPException(400, f"Invalid backup_manifest.json: {exc}") from exc

        discovered: list[dict[str, Any]] = []
        for acc in manifest.get("accounts") or []:
            email_addr = str(acc.get("email") or "").strip().lower()
            local_part = str(acc.get("local_part") or "").strip().lower()
            domain = str(acc.get("domain") or "").strip().lower()
            if not email_addr or "@" not in email_addr:
                continue
            if not local_part or not domain:
                local_part, _, domain = email_addr.partition("@")
            if not DOMAIN_RE.match(domain) or not LOCAL_RE.match(local_part):
                continue

            mbox_dir = base_dir / "mailboxes" / email_addr
            messages_file = mbox_dir / "messages.json"
            parsed_messages: list[dict[str, Any]] = []

            if messages_file.is_file():
                try:
                    raw_list = json.loads(messages_file.read_text(encoding="utf-8"))
                except Exception:
                    raw_list = []
                for m in raw_list:
                    rel_path = str(m.get("rel_path") or "")
                    if not rel_path or ".." in Path(rel_path).parts:
                        continue
                    eml_path = mbox_dir / rel_path
                    if not eml_path.is_file():
                        continue
                    parsed_messages.append(
                        {
                            "eml_path": eml_path,
                            "target_folder": str(m.get("target_folder") or "INBOX"),
                            "role": str(m.get("role") or "inbox"),
                            "flags": list(m.get("flags") or []),
                            "internal_ts": _clamp_ts(float(m.get("internal_ts") or time.time())),
                            "message_id": str(m.get("message_id") or "")[:500],
                            "subject": str(m.get("subject") or "")[:500],
                            "sender": str(m.get("sender") or "")[:320],
                            "recipients": list(m.get("recipients") or [])[:50],
                            "size": int(m.get("size") or eml_path.stat().st_size),
                            "has_attachment": bool(m.get("has_attachment")),
                        }
                    )

            acc_hash = normalize_cpanel_shadow_hash(str(acc.get("password_hash") or "")) or shadow_hashes.get(email_addr, "")
            discovered.append(
                {
                    "email": email_addr,
                    "local_part": local_part,
                    "domain": domain,
                    "quota_mb": int(acc.get("quota_mb") or 1024),
                    "password_hash": acc_hash,
                    "messages": parsed_messages,
                }
            )
        if discovered:
            return discovered

    # Fallback: Scan for raw Maildir structure (<domain>/<local_part>/{cur,new,.Sent,...})
    candidate_user_dirs: dict[str, Path] = {}
    for sub in extract_dir.rglob("*"):
        if not sub.is_dir():
            continue
        if sub.name in ("cur", "new"):
            parent = sub.parent
            user_dir = parent.parent if parent.name.startswith(".") else parent
            dom_dir = user_dir.parent
            local_part = user_dir.name.lower()
            domain = dom_dir.name.lower()
            if DOMAIN_RE.match(domain) and LOCAL_RE.match(local_part):
                candidate_user_dirs[f"{local_part}@{domain}"] = user_dir

    # Also include accounts present in shadow files even if their Maildir was empty
    for email_addr in shadow_hashes:
        if email_addr not in candidate_user_dirs:
            candidate_user_dirs[email_addr] = extract_dir / "__empty__"

    if not candidate_user_dirs:
        raise HTTPException(
            400,
            "No valid email accounts found in the uploaded archive. "
            "Upload the .tar.gz file generated by cpanel-migrate.sh or a cPanel mail/ directory archive.",
        )

    discovered = []
    for email_addr in sorted(candidate_user_dirs.keys()):
        user_dir = candidate_user_dirs[email_addr]
        local_part, _, domain = email_addr.partition("@")
        parsed_messages = _scan_maildir_folder_tree(user_dir) if user_dir.is_dir() else []
        discovered.append(
            {
                "email": email_addr,
                "local_part": local_part,
                "domain": domain,
                "quota_mb": 1024,
                "password_hash": shadow_hashes.get(email_addr, ""),
                "messages": parsed_messages,
            }
        )
    return discovered


def _scan_maildir_folder_tree(user_dir: Path) -> list[dict[str, Any]]:
    folders: list[tuple[Path, str, str]] = [(user_dir, "INBOX", "inbox")]
    for child in sorted(user_dir.iterdir()):
        if child.is_dir() and child.name.startswith(".") and not child.name.startswith(".cpanel"):
            tf, role = map_folder_name(child.name, [], ".")
            folders.append((child, tf, role))

    messages: list[dict[str, Any]] = []
    for folder_dir, target_folder, role in folders:
        for sub_name, default_seen in (("cur", True), ("new", False)):
            sub_dir = folder_dir / sub_name
            if not sub_dir.is_dir():
                continue
            for fpath in sorted(sub_dir.iterdir()):
                if not fpath.is_file() or fpath.name.startswith(("dovecot", "maildir")):
                    continue
                try:
                    raw_bytes = fpath.read_bytes()
                except OSError:
                    continue
                if not raw_bytes:
                    continue
                flags = []
                if ":2," in fpath.name:
                    fchars = fpath.name.rsplit(":2,", 1)[1]
                    if "S" in fchars:
                        flags.append("\\Seen")
                    if "F" in fchars:
                        flags.append("\\Flagged")
                    if "R" in fchars:
                        flags.append("\\Answered")
                    if "D" in fchars:
                        flags.append("\\Draft")
                elif default_seen:
                    flags.append("\\Seen")
                mtime = fpath.stat().st_mtime
                messages.append(
                    parse_eml_bytes(
                        raw_bytes=raw_bytes,
                        flags=flags,
                        internal_ts=mtime,
                        target_folder=target_folder,
                        role=role,
                        eml_path=fpath,
                    )
                )
    return messages


def _existing_mids_in_imap_folder(conn: imaplib.IMAP4, folder: str) -> set[str]:
    typ, _ = conn.select(_imap_quote(folder), readonly=True)
    if typ != "OK":
        return set()
    typ, data = conn.uid("SEARCH", None, "ALL")
    if typ != "OK" or not data or not data[0]:
        return set()
    uids = data[0].split()
    if not uids:
        return set()
    existing: set[str] = set()
    batch = 100
    for i in range(0, len(uids), batch):
        chunk = b",".join(uids[i : i + batch]).decode("ascii")
        typ, fdata = conn.uid("FETCH", chunk, "(BODY.PEEK[HEADER.FIELDS (MESSAGE-ID)])")
        if typ != "OK" or not fdata:
            continue
        for part in fdata:
            if isinstance(part, tuple) and len(part) > 1 and isinstance(part[1], bytes):
                msg = email.message_from_bytes(part[1], policy=email.policy.default)
                mid = str(msg.get("Message-ID") or "").strip()
                if mid:
                    existing.add(mid)
    return existing


def _append_account_messages_to_dovecot(
    email_addr: str, messages: list[dict[str, Any]]
) -> tuple[int, int, dict[str, int]]:
    if not messages:
        return 0, 0, {}

    by_folder: dict[str, list[dict[str, Any]]] = {}
    for m in messages:
        tf = m.get("target_folder") or "INBOX"
        by_folder.setdefault(tf, []).append(m)

    folder_counts: dict[str, int] = {}
    if settings.dev_mode:
        for tf, items in by_folder.items():
            folder_counts[tf] = len(items)
        return len(messages), 0, folder_counts

    try:
        conn = imaplib.IMAP4(settings.imap_host, settings.imap_port, timeout=45)
        conn.login(f"{email_addr}*{settings.imap_master_user}", settings.imap_master_password)
    except Exception as exc:
        raise HTTPException(502, f"Could not connect to local Dovecot IMAP for {email_addr}: {exc}") from exc

    inserted = 0
    skipped = 0
    try:
        for folder, items in by_folder.items():
            qfolder = _imap_quote(folder)
            if folder.upper() != "INBOX":
                conn.create(qfolder)
                conn.subscribe(qfolder)

            seen_ids = _existing_mids_in_imap_folder(conn, folder)
            items.sort(key=lambda x: float(x.get("internal_ts") or 0))

            for meta in items:
                mid = str(meta.get("message_id") or "").strip()
                if mid and mid in seen_ids:
                    skipped += 1
                    continue
                eml_path: Path = meta["eml_path"]
                if not eml_path.is_file():
                    continue
                raw_bytes = eml_path.read_bytes()
                flags_list = [f for f in (meta.get("flags") or []) if f.lower() != "\\recent"]
                flags_str = "(" + " ".join(flags_list) + ")" if flags_list else "()"
                ts = _clamp_ts(float(meta.get("internal_ts") or time.time()))
                date_time = imaplib.Time2Internaldate(ts)

                typ, _ = conn.append(qfolder, flags_str, date_time, raw_bytes)
                if typ != "OK":
                    conn.create(qfolder)
                    conn.subscribe(qfolder)
                    typ, _ = conn.append(qfolder, flags_str, date_time, raw_bytes)
                if typ == "OK":
                    inserted += 1
                    folder_counts[folder] = folder_counts.get(folder, 0) + 1
                    if mid:
                        seen_ids.add(mid)
    finally:
        try:
            conn.logout()
        except Exception:
            pass

    return inserted, skipped, folder_counts


def import_discovered_accounts(
    db: Session,
    accounts: list[dict[str, Any]],
    allowed_domain_ids: set[int] | None = None,
    is_super: bool = True,
    use_cpanel_passwords: bool = True,
    reset_existing_passwords: bool = True,
) -> dict[str, Any]:
    """Import a list of discovered account dicts (each with email, local_part, domain,
    quota_mb, password_hash, messages) into MailSomadhan."""
    accounts_by_domain: dict[str, list[dict[str, Any]]] = {}
    for acc in accounts:
        accounts_by_domain.setdefault(acc["domain"], []).append(acc)

    domains_by_name: dict[str, Domain] = {}
    domains_created: list[str] = []

    for dom_name, dom_accounts in accounts_by_domain.items():
        domain = db.query(Domain).filter_by(name=dom_name).first()
        if not domain:
            if not is_super:
                raise HTTPException(
                    403, f"Domain {dom_name} does not exist yet. Only a super administrator can create new domains."
                )
            limit = int(get_setting(db, "default_domain_storage_mb") or 0)
            default_q = int(get_setting(db, "default_quota_mb") or 0)
            if default_q == UNLIMITED and (limit != UNLIMITED or max_mailbox_mb(db) != UNLIMITED):
                default_q = smallest(1024, max_mailbox_mb(db), limit)
            domain = Domain(
                name=dom_name,
                default_quota_mb=smallest(default_q, max_mailbox_mb(db), limit) if default_q else UNLIMITED,
                storage_limit_mb=limit,
                active=True,
            )
            generate_dkim(domain)
            db.add(domain)
            db.commit()
            db.refresh(domain)
            write_selector_map(db)
            if auto_enabled(db):
                try:
                    ensure_postmaster(db, domain)
                except Exception:
                    db.rollback()
            domains_created.append(dom_name)
        else:
            if allowed_domain_ids is not None and domain.id not in allowed_domain_ids:
                raise HTTPException(403, f"You do not have permission to import into domain {dom_name}")

        if domain.storage_limit_mb != UNLIMITED:
            existing_alloc = sum(
                m.quota_mb for m in db.query(Mailbox).filter_by(domain_id=domain.id).all() if m.quota_mb != UNLIMITED
            )
            needed_alloc = sum(int(a.get("quota_mb") or 1024) for a in dom_accounts)
            if existing_alloc + needed_alloc > domain.storage_limit_mb:
                domain.storage_limit_mb = existing_alloc + needed_alloc + 10240
                db.commit()

        domains_by_name[dom_name] = domain

    local_domain_names = {d.name.lower() for d in db.query(Domain).all()}
    results: list[dict[str, Any]] = []
    total_imported_msgs = 0
    total_skipped_msgs = 0

    for acc in accounts:
        email_addr = acc["email"]
        local_part = acc["local_part"]
        dom_name = acc["domain"]
        domain = domains_by_name[dom_name]
        messages: list[dict[str, Any]] = acc.get("messages") or []
        cpanel_hash = str(acc.get("password_hash") or "").strip()

        total_bytes = sum(int(m.get("size") or 0) for m in messages)
        min_needed_mb = int(total_bytes / (1024 * 1024)) + 512
        max_mb = max_mailbox_mb(db)
        desired_quota = max(int(acc.get("quota_mb") or 1024), min_needed_mb, 1024)
        if max_mb != UNLIMITED:
            desired_quota = min(desired_quota, max_mb)

        conflict_alias = db.query(Alias).filter_by(source=email_addr).first()
        if conflict_alias:
            db.delete(conflict_alias)
            db.commit()

        if use_cpanel_passwords and cpanel_hash:
            target_hash = cpanel_hash
            password_out = "(same as cPanel)"
            password_mode = "cpanel"
        else:
            new_password = generate_random_password(16)
            target_hash = hash_password(new_password)
            password_out = new_password
            password_mode = "random"

        mbox = db.query(Mailbox).filter_by(email=email_addr).first()
        created_new = False

        if not mbox:
            created_new = True
            mbox = Mailbox(
                domain_id=domain.id,
                local_part=local_part,
                email=email_addr,
                password_hash=target_hash,
                display_name=local_part,
                quota_mb=desired_quota,
                active=True,
            )
            db.add(mbox)
            db.commit()
        else:
            if reset_existing_passwords:
                mbox.password_hash = target_hash
                mbox.token_version += 1
            else:
                password_out = "(unchanged)"
                password_mode = "unchanged"
            if mbox.quota_mb != UNLIMITED and mbox.quota_mb < desired_quota:
                mbox.quota_mb = desired_quota
            mbox.active = True
            db.commit()

        ins_count, skip_count, folder_counts = _append_account_messages_to_dovecot(email_addr, messages)
        total_imported_msgs += ins_count
        total_skipped_msgs += skip_count

        existing_mids = {
            row[0]
            for row in db.query(MailMessage.message_id)
            .filter(
                MailMessage.message_id != "",
                (MailMessage.user_email == email_addr) | (MailMessage.sender == email_addr),
            )
            .all()
        }
        added_logs = 0
        for meta in messages:
            role = meta.get("role") or ""
            tf = (meta.get("target_folder") or "").upper()
            if role not in ("inbox", "sent") and tf not in ("INBOX", "SENT"):
                continue
            mid = str(meta.get("message_id") or "").strip()[:500]
            if mid and mid in existing_mids:
                continue

            when = datetime.datetime.fromtimestamp(
                _clamp_ts(float(meta.get("internal_ts") or time.time())), tz=datetime.timezone.utc
            )
            sender = str(meta.get("sender") or "").lower()[:320]
            sender_dom = sender.rpartition("@")[2] if "@" in sender else ""
            rcpts = [str(r).lower()[:320] for r in (meta.get("recipients") or []) if "@" in str(r)]
            is_sent = role == "sent" or tf == "SENT" or sender == email_addr

            if is_sent:
                if not sender:
                    sender, sender_dom = email_addr, dom_name
                if not rcpts:
                    continue
                ext_count = sum(1 for r in rcpts if r.rpartition("@")[2] not in local_domain_names)
                direction = "outbound" if ext_count > 0 else "internal"
                user_email_val = email_addr
                source_val = "webmail"
            else:
                if email_addr not in rcpts:
                    rcpts = [email_addr]
                ext_count = 0
                direction = "internal" if sender_dom in local_domain_names else "inbound"
                user_email_val = sender if sender_dom in local_domain_names else ""
                source_val = "smtp"

            mm = MailMessage(
                queue_id=None,
                created_at=when,
                finished_at=when,
                source=source_val,
                sasl_user=email_addr if is_sent else "",
                user_email=user_email_val,
                sender=sender,
                sender_domain=sender_dom[:253],
                message_id=mid,
                subject=str(meta.get("subject") or "")[:500],
                size=int(meta.get("size") or 0),
                nrcpt=len(rcpts),
                direction=direction,
                status="delivered",
                has_attachment=bool(meta.get("has_attachment")),
                external_rcpts=ext_count,
            )
            for r in rcpts[:25]:
                r_dom = r.rpartition("@")[2][:253]
                mm.deliveries.append(
                    MailDelivery(
                        recipient=r,
                        recipient_domain=r_dom,
                        orig_recipient=r,
                        is_local=r_dom in local_domain_names,
                        status="sent",
                        dsn="2.0.0",
                        relay="cpanel-import",
                        delay=0.0,
                        response="250 2.0.0 Imported from cPanel backup",
                        updated_at=when,
                    )
                )
            db.add(mm)
            if mid:
                existing_mids.add(mid)
            added_logs += 1

        if added_logs:
            db.commit()

        results.append(
            {
                "email": email_addr,
                "domain": dom_name,
                "password": password_out,
                "password_mode": password_mode,
                "created": created_new,
                "messages_imported": ins_count,
                "messages_skipped": skip_count,
                "folders": folder_counts,
            }
        )

    return {
        "domains_created": domains_created,
        "mailboxes_total": len(results),
        "messages_imported": total_imported_msgs,
        "messages_skipped": total_skipped_msgs,
        "accounts": results,
    }


def import_backup_archive(
    db: Session,
    archive_path: Path,
    allowed_domain_ids: set[int] | None = None,
    is_super: bool = True,
    use_cpanel_passwords: bool = True,
    reset_existing_passwords: bool = True,
) -> dict[str, Any]:
    """Extract and import a cPanel backup archive into MailSomadhan."""
    with tempfile.TemporaryDirectory(prefix="ms-cpanel-import-") as tmpdir:
        extract_dir = Path(tmpdir)
        _safe_extract_archive(archive_path, extract_dir)
        accounts = _discover_accounts_from_extracted(extract_dir)
        return import_discovered_accounts(
            db=db,
            accounts=accounts,
            allowed_domain_ids=allowed_domain_ids,
            is_super=is_super,
            use_cpanel_passwords=use_cpanel_passwords,
            reset_existing_passwords=reset_existing_passwords,
        )
